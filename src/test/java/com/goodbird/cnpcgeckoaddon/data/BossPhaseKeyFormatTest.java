    @Test
    @DisplayName("a saved phase carries exactly the keys the format promises")
    void thePhaseSaveFormatIsUnchanged() {
        assertEquals(new TreeSet<>(EXPECTED_KEYS),
                new TreeSet<>(new BossPhaseData().writeToNBT().getAllKeys()),
                "the phase save format changed - a key was renamed, added or lost");
    }

    @Test
    @DisplayName("everything a phase writes it also reads back")
    void everyKeyIsReadBack() {
        BossPhaseData written = new BossPhaseData();
        CompoundTag tag = written.writeToNBT();
        BossPhaseData reloaded = new BossPhaseData();
        reloaded.readFromNBT(tag);
        assertEquals(new TreeSet<>(tag.getAllKeys()),
                new TreeSet<>(reloaded.writeToNBT().getAllKeys()));
    }
